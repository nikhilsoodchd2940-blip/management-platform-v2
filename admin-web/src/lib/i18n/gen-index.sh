#!/bin/sh
# Regenerates dictionaries/index.ts from the files in this folder.
cd "$(dirname "$0")/dictionaries" || exit 1
{
  echo "// AUTO-GENERATED by ../gen-index.sh — run it after adding a dictionary file."
  for f in $(ls *.ts | grep -v '^index.ts$' | sed 's/\.ts$//'); do
    echo "import $f from './$f';"
  done
  echo
  echo "export const NAMESPACES = {"
  for f in $(ls *.ts | grep -v '^index.ts$' | sed 's/\.ts$//'); do
    echo "  $f,"
  done
  echo "};"
} > index.ts
